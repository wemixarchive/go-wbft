func makeGenesis(signers []account) *types.Header {
	header := &types.Header{
		Number:     big.NewInt(0),
		Time:       uint64(time.Now().UnixNano()),
		Difficulty: types.QBFTDefaultDifficulty,
	}

	e := new(types.EpochInfo)
	for i, s := range signers {
		e.Stakers = append(e.Stakers, &types.Staker{Addr: s.addr, Diligence: 1900000})
		e.Validators = append(e.Validators, uint32(i))
	}
	ApplyHeaderQBFTExtra(header, WriteEpochInfo(e))
	return header
}

func makeHeader(parent *types.Header) *types.Header {
	header := types.CopyHeader(parent)
	header.Number.Add(header.Number, big.NewInt(1))
	header.Time = uint64(time.Now().UnixNano())

	return header
}

func makePrepareSeal(h *types.Header, node account) []byte {
	seal, err := crypto.Sign(qbftcore.PrepareSeal(h, 0, qbftcore.SealTypePrepare), node.key)
	if err != nil {
		panic(err)
	}
	return seal
}

func makeCommitSeal(h *types.Header, node account) []byte {
	seal, err := crypto.Sign(qbftcore.PrepareSeal(h, 0, qbftcore.SealTypeCommit), node.key)
	if err != nil {
		panic(err)
	}
	return seal
}
